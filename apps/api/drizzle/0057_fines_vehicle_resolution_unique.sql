-- ============================================================
-- 0057 — P3 #701 (код-аудит 2026-06-14): БД-дедуп штрафов.
--
-- fines.worker дедуплицировал найденные штрафы только на уровне приложения
-- (in-memory Set), причём Set не обновлялся после вставок → один и тот же
-- (vehicle_id, resolution_number) мог вставиться дважды в одном прогоне, а
-- параллельные прогоны не имели никакой защиты от дублей.
--
-- Добавляем частичный UNIQUE по (vehicle_id, resolution_number). Частичный —
-- т.к. resolution_number nullable (ручные штрафы без номера постановления не
-- должны конфликтовать между собой). Воркер переведён на onConflictDoNothing,
-- так что после применения индекса гонки/повторы тихо игнорируются.
--
-- Если CREATE UNIQUE INDEX упадёт — в данных уже есть дубли (последствие старого
-- поведения), их нужно реконсилировать перед повторным прогоном миграции.
-- BEGIN/COMMIT — атомарность (docs/architecture/migrations.md §2).
-- ============================================================
BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS idx_fines_vehicle_resolution
    ON fines (vehicle_id, resolution_number)
    WHERE resolution_number IS NOT NULL;

COMMIT;
