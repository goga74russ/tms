-- 0040 — E6 (JWT revocation, Вариант A): users.token_version.
--
-- JWT сейчас stateless: сервер не ходит в БД, поэтому токен нельзя отозвать
-- досрочно (деактивированный/перенастроенный юзер живёт до истечения 24ч).
-- Монотонный token_version кладётся в JWT при логине; authenticate-decorator
-- сверяет с БД и отвергает токены со старой версией. Бамп версии (деактивация/
-- смена пароля/ролей) → все старые токены пользователя мгновенно невалидны.
--
-- BEGIN/COMMIT — атомарность (docs/architecture/migrations.md §2).
-- ============================================================
BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version integer NOT NULL DEFAULT 0;

COMMIT;
